"""Write boston_city.yaml and boston_city_epi.yaml from the two CSV tables here.

    python systems/make_boston.py

Illustrative, not calibrated. What is assumed:
  * populations: 2020 Census neighborhood totals, rounded; the age split is approximate
  * coordinates: rough neighborhood centroids and hospital campuses
  * vulnerability: a hand-set weight standing in for a social vulnerability index
  * beds: MassGIS ICU and med-surg beds (healthcare/hospitals), times BOSTON_SHARE,
    the share assumed to serve Boston residents; BIDMC is East + West
  * travel: straight-line km x ROAD_FACTOR at CITY_KMH, plus DOOR_MIN
  * mixing: Omicron fit's age contacts; neighborhood coupling from a distance kernel
  * disease: covid_omicron preset with the Massachusetts fit (scenarios/omicron_2021.yaml),
    seeded with Boston's population share of the statewide seed
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from cascade.epi import coupling_from_distance, haversine_km

HERE = Path(__file__).resolve().parent
BOSTON_SHARE = 0.35
ROAD_FACTOR, CITY_KMH, DOOR_MIN = 1.35, 24.0, 5.0
STATE_SEED, STATE_POP = 71300, 7_030_000


def build() -> tuple[dict, dict]:
    nb = pd.read_csv(HERE / "boston_neighborhoods.csv")
    hosp = pd.read_csv(HERE / "boston_hospitals.csv")
    counts = nb[["age_0_17", "age_18_64", "age_65_plus"]].to_numpy()
    pop = counts.sum(axis=1)

    d_nb = haversine_km(nb.lat, nb.lon)
    W = np.round(coupling_from_distance(d_nb, scale_km=2.0, home_share=0.75, population=pop), 4)
    np.fill_diagonal(W, 0.0)
    np.fill_diagonal(W, np.round(1.0 - W.sum(axis=1), 4))      # rows sum to 1 after rounding

    lat = np.r_[nb.lat, hosp.lat]
    lon = np.r_[nb.lon, hosp.lon]
    d_nh = haversine_km(lat, lon)[: len(nb), len(nb):]
    travel = DOOR_MIN + d_nh * ROAD_FACTOR / CITY_KMH * 60

    seed = STATE_SEED * pop.sum() / STATE_POP
    epi = {
        "disease": {"preset": "covid_omicron", "r0": 1.95, "hosp_scale": 1.08},
        "population": {"patches": nb.patch.tolist(), "ages": ["0-17", "18-64", "65+"],
                       "counts": counts.tolist()},
        "mixing": {
            "age_contacts": [[9.00, 8.09, 0.96], [2.50, 10.47, 1.18], [1.11, 4.40, 1.80]],
            "patch_coupling": W.tolist(),
        },
        "seeding": {"exposed": {p: round(float(seed * n / pop.sum()), 1)
                                for p, n in zip(nb.patch, pop)},
                    "immune_share": 0.22},
        "sim": {"start": "2021-12-01", "days": 120, "substeps": 4, "stochastic": False},
    }
    system = {
        "epi": "boston_city_epi.yaml",
        "network": {
            "hospitals": [
                {"id": h.id, "ccn": str(h.ccn), "name": h.name,
                 "ward_beds": round(h.ward_beds * BOSTON_SHARE), "icu_beds": round(h.icu_beds * BOSTON_SHARE),
                 "er": bool(h.er), "baseline_occupancy": 0.75}
                for h in hosp.itertuples()
            ],
            "travel_minutes": np.round(travel, 1).tolist(),
        },
        "allocation": {"decay": 0.08},
        "rerouting": {"p_on": 40, "p_off": 50, "occ_on": 0.95, "occ_off": 0.90, "min_open": 2},
        "equity": {"vulnerability": dict(zip(nb.patch, nb.vulnerability.astype(float)))},
        "events": [],
    }
    return system, epi


HEADER = "# Generated by systems/make_boston.py from the CSV tables next to it. Illustrative, not calibrated.\n"


def main() -> None:
    system, epi = build()
    for name, obj in (("boston_city.yaml", system), ("boston_city_epi.yaml", epi)):
        text = yaml.safe_dump(obj, sort_keys=False, default_flow_style=None, width=110)
        (HERE / name).write_text(HEADER + text)
        print("wrote", HERE / name)


if __name__ == "__main__":
    main()
